#!/usr/bin/env python3
"""Assemble distributable Mata source without duplicating maintained code.

Run: python3 build.py [--check]
This does not compile Mata; compilation is performed by Stata on first use.
"""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parent
MODULES = (
    "jwselect_types.mata", "jwselect_design.mata", "jwselect_candidates.mata",
    "jwselect_core.mata", "jwselect_select.mata", "jwselect_infer.mata",
    "jwselect_reselect.mata", "jwselect_jobs.mata",
    "jwselect_bridge.mata",
)


def render():
    parts = ["*! Generated by build.py; edit the source modules in the mata directory, not this file.\n"
             "*! jwselect 0.4.0 23oct2026; build joint1\nversion 16.1\nmata:\n"]
    for name in MODULES:
        parts.append(f"\n/* ===== {name} ===== */\n")
        parts.append((ROOT / "mata" / name).read_text().rstrip() + "\n")
    parts.append("\nend\n")
    return "".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "_jwselect_mata.do"
    expected = render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            sys.exit("FAIL: _jwselect_mata.do is stale; run python3 build.py")
        print(f"PASS: generated Mata loader matches all {len(MODULES)} source modules")
    else:
        target.write_text(expected)
        print(f"Built {target.name} from {len(MODULES)} modules")
